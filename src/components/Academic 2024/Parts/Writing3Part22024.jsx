import React, { useState } from "react";
import { IoIosArrowDown } from "react-icons/io";
import { toast, ToastContainer } from "react-toastify";
import "react-toastify/dist/ReactToastify.css";



import Writing3Pagination2024 from "../Pagination 2024/Writing3Pagination2024";

const Writing3Part22024 = () => {
  const [message, setMessage] = useState("");
  const [sentenceCount, setSentenceCount] = useState(0);
  const [submittedMessage, setSubmittedMessage] = useState("");

  const [openScript, setOpenScript] = useState(true);

  // The key used by the home page
  const storageKey = "/Writing1Part22019";

  // Load mark from localStorage if it exists
  const [mark, setMark] = useState(
    Number(localStorage.getItem(storageKey)) || null,
  );

  const handleSubmit = (e) => {
    e.preventDefault();

    // Count words
    const rawWords = message.split(/\s+/).filter((s) => s.length > 0);
    const wordCount = rawWords.length;

    setSentenceCount(wordCount);

    if (wordCount < 1) {
      toast.warn("Please write at least one word!", { autoClose: 3000 });
    } else {
      toast.success(`You wrote ${wordCount} words`, { autoClose: 3000 });
    }

    // Set mark if more than 5 words
    const newMark = wordCount > 5 ? 1 : null;
    setMark(newMark);

    // Save mark in localStorage using the home page key
    if (newMark !== null) {
      localStorage.setItem(storageKey, newMark);
    } else {
      localStorage.removeItem(storageKey);
    }

    setSubmittedMessage(message);
  };

  return (
    <div className="px-3">
      <div className="flex gap-6 ">
        {/* LEFT SIDE */}
        <div className="w-1/2 bg-white space-y-5 rounded-lg shadow-md p-6 overflow-y-scroll h-[1000px]">
          <div className="flex justify-between items-center">
            <h1 className="text-2xl font-bold">TASK 2</h1>
          </div>

          <div className="">
            <h1 className="text-xl mb-4">
              You should spend about 40 minutes on this task.
            </h1>
            <p className="text-xl mb-4">Write about the following topic:</p>
            <p className="text-lg p-5 font-bold italic border-2 border-black">
              It is important for everyone, including young people, to save
              money for their future. To what extent do you agree or disagree
              with this statement?
            </p>
            <p className="text-xl my-4">
              Give reasons for your answer and include any relevant examples
              from your own knowledge or experience.
            </p>
            <p className="text-lg mt-4">Write at least 250 words.</p>
            <br />

            <br />
            <hr className="border border-gray-400" />
            <br />

            <div className="flex justify-between items-center">
              <p onClick={() => setOpenScript(!openScript)}>
                Sample Writing Answer
              </p>
              <span onClick={() => setOpenScript(!openScript)}>
                <IoIosArrowDown size={20} />
              </span>
            </div>
            <br />
            {/* left text */}
            {openScript ? (
              <div>
                <h1 className="text-xl text-center font-bold">
                  The Importance of Young People's Saving for the Future
                </h1>
                <p className="mt-5">
                  Saving money is crucial for everyone, especially young people.
                  It acts as a safety net against life's unexpected challenges,
                  like job loss or health issues, while also laying the
                  groundwork for long-term goals. Some argue that youth should
                  focus on enjoying the present, but planning ahead through
                  savings ensures a more secure future rather than relying on
                  luck or last-minute fixes. <br /> <br /> The 2008 financial crisis serves as
                  a powerful example. Many young professionals faced sudden
                  unemployment and financial chaos, and those without savings
                  struggled to pay for basics, often turning to credit or family
                  support and falling into long-term debt. This showed that
                  savings are essential: they help us survive economic storms
                  without derailing our lives. Even short-term setbacks can
                  become long-term problems without savings, limiting
                  opportunities for education or career growth. <br /> <br /> Saving also
                  helps achieve major life milestones, like buying a house or
                  starting a business, which require discipline and early
                  preparation. Small, consistent savings from a young age add up
                  significantly over time thanks to the power of compounding.
                  Starting in your 20s means your money has decades to grow,
                  making goals more achievable than waiting until later when
                  expenses and responsibilities often increase. This reduces
                  reliance on loans and brings financial independence closer. <br /> <br />
                  Critics may say low early-career incomes make saving hard, but
                  the key is building the habit. Even small, regular savings
                  teach financial discipline, a skill that becomes more valuable
                  as earnings rise. Saving isn't about sacrificing the present;
                  it's about balance - meeting current needs while preparing for
                  the future. For young people, starting early means gaining the
                  confidence to handle uncertainty, pursue dreams without heavy
                  debt, and build a foundation for a stable, empowered life.
                </p>
              </div>
            ) : (
              <>
                {" "}
                <hr className=" border border-gray-400 border-dotted" />
              </>
            )}
          </div>
        </div>

        {/* RIGHT SIDE */}
        <div className="w-1/2 bg-white space-y-5 rounded-lg shadow-md p-6 overflow-y-scroll h-[1000px]">
          <textarea
            rows="16"
            placeholder="Please input"
            className="border border-gray-400 rounded-lg w-full p-3 focus:outline-none focus:ring-2 focus:ring-blue-500"
            value={message}
            onChange={(e) => setMessage(e.target.value)}
          ></textarea>

          <div className="flex justify-between p-4">
            <h3 className="mt-3">Words: {sentenceCount}</h3>
            <input
              onClick={handleSubmit}
              type="submit"
              value="Submit for Feedback"
              className="bg-blue-500 text-white px-4 py-2 rounded-2xl cursor-pointer hover:bg-blue-600 transition"
            />
          </div>

          {/* MARK */}
          {mark !== null && (
            <div className="flex justify-center mt-4">
              <div className="bg-green-100 text-green-800 px-8 py-4 rounded-2xl font-bold shadow-lg">
                Mark: {mark}
              </div>
            </div>
          )}

          {/* Submitted Message */}
          <h1 className="text-2xl font-bold mt-6">Writing Feedback</h1>
          <div className="bg-gray-300 p-5 mt-4 rounded-lg min-h-[100px]">
            <p>{submittedMessage}</p>
          </div>

          <ToastContainer />
        </div>
      </div>
      <Writing3Pagination2024></Writing3Pagination2024>
    </div>
  );
};

export default Writing3Part22024;
